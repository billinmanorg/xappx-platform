#!/usr/bin/env node
// Bundles the XAPPX Factory console (apps/app-factory) into this site's Netlify
// function at netlify/functions/admin.mjs, so xappx.ai/admin is served by
// Netlify instead of a separate always-on server.
//
// What it does:
//   1. compiles apps/app-factory with its own TypeScript (tsc)
//   2. copies the compiled server modules into netlify/functions/admin-lib/
//   3. inlines packages/design-system/tokens.css as admin-lib/tokens.js
//
// Run it before every deploy of apps/web (the output folder is git-ignored):
//   node scripts/prepare-admin.mjs
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "..");
const repo = resolve(web, "..", "..");
const factory = join(repo, "apps", "app-factory");
const tokens = join(repo, "packages", "design-system", "tokens.css");
const out = join(web, "netlify", "functions", "admin-lib");

if (!existsSync(join(factory, "node_modules"))) {
  console.log("prepare-admin: installing app-factory dependencies");
  execFileSync("npm", ["ci", "--no-audit", "--no-fund"], { cwd: factory, stdio: "inherit", shell: true });
}
console.log("prepare-admin: compiling app-factory");
execFileSync("npm", ["run", "build"], { cwd: factory, stdio: "inherit", shell: true });

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const f of ["main.js", "render.js", "api.js", "llm.js"]) {
  cpSync(join(factory, "dist", "src", f), join(out, f));
}
writeFileSync(
  join(out, "tokens.js"),
  `// generated by scripts/prepare-admin.mjs — do not edit\nexport const tokensCss = ${JSON.stringify(readFileSync(tokens, "utf8"))};\n`,
);
console.log(`prepare-admin: wrote ${out}`);
